"""Builds worker.js (Cloudflare) with Maya's prompts + the lesson list inside it.
Run again after every change to prompts/*.txt or curriculum.json:  python build_worker.py
Then paste worker.js into Cloudflare (or deploy it)."""
import json
import os

here = os.path.dirname(os.path.abspath(__file__))
read = lambda name: open(os.path.join(here, name), encoding="utf-8").read()

prompts = {name: read(f"prompts/{name}.txt") for name in ("base", "onboarding", "lesson", "free")}
lessons = {}
for level in json.loads(read("curriculum.json"))["levels"]:
    for lesson in level["lessons"]:
        lessons[lesson["id"]] = {"level": f"{level['title']} ({level['cefr']})", "title": lesson["title"], "words": lesson["words"]}

worker = r'''// Speakuru API — Cloudflare Worker (Maya's brain).
// GENERATED by build_worker.py from prompts/*.txt and curriculum.json — edit those, then rebuild.
// The DeepSeek key is stored in Cloudflare as a secret named DEEPSEEK_API_KEY.

const PROMPTS = __PROMPTS__;
const LESSONS = __LESSONS__;

const TAP_ONLY = "TAP-ONLY MODE: the student cannot speak or type right now. Never use SPEAK. " +
  "Every message must end with a CHOICES, QUIZ, BUILD or LISTEN tag so they can answer by tapping. " +
  "In role-plays, always give CHOICES.";

// Websites allowed to use this API
const ALLOWED = [/^https:\/\/[a-z0-9-]+\.github\.io$/i, /^http:\/\/localhost(:\d+)?$/, /^https:\/\/(www\.)?speakuru\.com$/];

function cors(origin) {
  const ok = ALLOWED.some((r) => r.test(origin || ""));
  return {
    "Access-Control-Allow-Origin": ok ? origin : "null",
    "Access-Control-Allow-Methods": "POST, OPTIONS",
    "Access-Control-Allow-Headers": "Content-Type",
    "Vary": "Origin",
  };
}

function json(obj, status, headers) {
  return new Response(JSON.stringify(obj), { status, headers: { ...headers, "Content-Type": "application/json" } });
}

// Same logic as build_system() in server.py — keep both in sync.
function buildSystem(body) {
  const mode = ["onboarding", "lesson", "free"].includes(body.mode) ? body.mode : "onboarding";
  let system = PROMPTS.base + "\n\n" + PROMPTS[mode];
  if (mode === "lesson") {
    const l = LESSONS[String(body.lessonId || "")];
    if (l) system += `\n\nTODAY'S LESSON:\nLevel: ${l.level}\nLesson: ${l.title}\nKey words: ${l.words.join(", ")}`;
  }
  if (body.tapOnly) system += "\n\n" + TAP_ONLY;
  if (body.profile && typeof body.profile === "object" && Object.keys(body.profile).length) {
    system += "\n\nWHAT YOU ALREADY KNOW ABOUT THIS STUDENT:\n" + JSON.stringify(body.profile).slice(0, 500);
  }
  return system;
}

export default {
  async fetch(request, env) {
    const origin = request.headers.get("Origin");
    const headers = cors(origin);
    if (request.method === "OPTIONS") return new Response(null, { headers });
    if (request.method !== "POST" || new URL(request.url).pathname !== "/api/chat") return json({ error: "not_found" }, 404, headers);
    if (!ALLOWED.some((r) => r.test(origin || ""))) return json({ error: "forbidden" }, 403, headers);
    if (!env.DEEPSEEK_API_KEY) return json({ error: "no_key" }, 500, headers);

    let body;
    try { body = await request.json(); } catch { return json({ error: "bad_request" }, 400, headers); }

    // keep requests small (protects your DeepSeek credit)
    const messages = (Array.isArray(body.messages) ? body.messages : [])
      .slice(-30)
      .filter((m) => m && (m.role === "user" || m.role === "assistant") && typeof m.content === "string")
      .map((m) => ({ role: m.role, content: m.content.slice(0, 1500) }));
    if (!messages.length) return json({ error: "bad_request" }, 400, headers);

    const r = await fetch("https://api.deepseek.com/chat/completions", {
      method: "POST",
      headers: { "Content-Type": "application/json", Authorization: "Bearer " + env.DEEPSEEK_API_KEY },
      body: JSON.stringify({
        model: "deepseek-chat",
        messages: [{ role: "system", content: buildSystem(body) }, ...messages],
        temperature: 0.7,
        max_tokens: 500,
      }),
    });
    if (!r.ok) return json({ error: "deepseek_" + r.status }, 502, headers);
    const data = await r.json();
    return json({ reply: data.choices[0].message.content }, 200, headers);
  },
};
'''
out = worker.replace("__PROMPTS__", json.dumps(prompts, ensure_ascii=False)).replace("__LESSONS__", json.dumps(lessons, ensure_ascii=False))
open(os.path.join(here, "worker.js"), "w", encoding="utf-8").write(out)
print("worker.js built")
